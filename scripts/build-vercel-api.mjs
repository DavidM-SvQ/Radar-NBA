import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { build } from 'esbuild';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const outDir = path.join(rootDir, 'api');
const outFile = path.join(outDir, 'index.js');

fs.mkdirSync(outDir, { recursive: true });

await build({
  entryPoints: [path.join(rootDir, 'src', 'server', 'vercelEntry.ts')],
  outfile: outFile,
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  packages: 'external',
  sourcemap: false,
  legalComments: 'none',
  banner: {
    js: '// Pre-compiled RadarNBA Vercel Serverless API bundle (auto-generated by scripts/build-vercel-api.mjs)\nif (!process.env.VERCEL) process.env.VERCEL = "1";\nif (!process.env.NBA_SNAPSHOT_ONLY) process.env.NBA_SNAPSHOT_ONLY = "1";',
  },
});

const stat = fs.statSync(outFile);
console.log(
  `[build-vercel-api] Built ${path.relative(rootDir, outFile)} (${(
    stat.size / 1024
  ).toFixed(1)} KB)`
);
